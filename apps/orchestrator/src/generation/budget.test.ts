import type { GenerationBudget } from '@simproof/contracts'
import { describe, expect, it } from 'vitest'

import { canStartProviderTurn, chargeArtifactBytes, chargeProviderTurn } from './budget.js'

const budget = (consumed: GenerationBudget['consumed']): GenerationBudget => ({
  limits: {
    maxProviderRequests: 2,
    maxInputTokens: 100,
    maxOutputTokens: 50,
    maxArtifactBytes: 1_000,
    maxCostMicrousd: 5_000,
  },
  consumed,
})

describe('generation budget', () => {
  it('reserves capacity before starting a provider turn', () => {
    expect(
      canStartProviderTurn(
        budget({
          providerRequests: 1,
          inputTokens: 0,
          outputTokens: 0,
          artifactBytes: 0,
          costMicrousd: 0,
        }),
      ),
    ).toBe(true)
    expect(
      canStartProviderTurn(
        budget({
          providerRequests: 2,
          inputTokens: 0,
          outputTokens: 0,
          artifactBytes: 0,
          costMicrousd: 0,
        }),
      ),
    ).toBe(false)
  })

  it('charges failed calls even when they report no token usage', () => {
    const result = chargeProviderTurn(
      budget({
        providerRequests: 1,
        inputTokens: 10,
        outputTokens: 5,
        artifactBytes: 0,
        costMicrousd: 100,
      }),
      { inputTokens: 0, outputTokens: 0, requestCount: 1, costMicrousd: 0 },
    )
    expect(result).toEqual({
      ok: true,
      value: budget({
        providerRequests: 2,
        inputTokens: 10,
        outputTokens: 5,
        artifactBytes: 0,
        costMicrousd: 100,
      }),
    })
  })

  it.each([
    [{ inputTokens: 91, outputTokens: 0, requestCount: 1, costMicrousd: 0 }, 'inputTokens'],
    [{ inputTokens: 0, outputTokens: 46, requestCount: 1, costMicrousd: 0 }, 'outputTokens'],
    [{ inputTokens: 0, outputTokens: 0, requestCount: 1, costMicrousd: 4_901 }, 'costMicrousd'],
  ] as const)('rejects token usage beyond the configured bound', (usage, dimension) => {
    const result = chargeProviderTurn(
      budget({
        providerRequests: 1,
        inputTokens: 10,
        outputTokens: 5,
        artifactBytes: 0,
        costMicrousd: 100,
      }),
      usage,
    )

    expect(result).toEqual({ ok: false, dimension })
  })

  it('uses the reported request count, including a pre-dispatch zero', () => {
    const current = budget({
      providerRequests: 1,
      inputTokens: 0,
      outputTokens: 0,
      artifactBytes: 0,
      costMicrousd: 0,
    })
    expect(
      chargeProviderTurn(current, {
        requestCount: 0,
        inputTokens: 0,
        outputTokens: 0,
        costMicrousd: 0,
      }),
    ).toEqual({ ok: true, value: current })
    expect(
      chargeProviderTurn(current, {
        requestCount: 2,
        inputTokens: 0,
        outputTokens: 0,
        costMicrousd: 0,
      }),
    ).toEqual({ ok: false, dimension: 'providerRequests' })
  })

  it('charges generated bytes without accepting a partial over-budget artifact', () => {
    const current = budget({
      providerRequests: 0,
      inputTokens: 0,
      outputTokens: 0,
      artifactBytes: 900,
      costMicrousd: 0,
    })
    expect(chargeArtifactBytes(current, 100)).toEqual({
      ok: true,
      value: budget({
        providerRequests: 0,
        inputTokens: 0,
        outputTokens: 0,
        artifactBytes: 1_000,
        costMicrousd: 0,
      }),
    })
    expect(chargeArtifactBytes(current, 101)).toEqual({
      ok: false,
      dimension: 'artifactBytes',
    })
  })
})
